/**
 * Returns a random quote from the Amma quotes collection.
 * Uses the current date as a seed for daily consistency,
 * so the same quote appears throughout the day but changes the next day.
 */
export const getDailyQuote = (): string => {
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const index = seed % AMMA_QUOTES.length;
  return AMMA_QUOTES[index];
};

/**
 * Returns a completely random quote (useful for pull-to-refresh).
 */
export const getRandomQuote = (): string => {
  return AMMA_QUOTES[Math.floor(Math.random() * AMMA_QUOTES.length)];
};
